// OpName is the name of an operation in a language: English when that language has none, the operation itself when no language has.
func OpName(lang, op string) string {
	if s, ok := OpNames[lang][op]; ok {
		return s
	}
	if s, ok := OpNames["en"][op]; ok {
		return s
	}
	return op
}
